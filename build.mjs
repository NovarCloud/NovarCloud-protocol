// Build: src/ -> dist/ (deploy output). Zero dependencies.
// Usage: node build.mjs [--out dir] [--ca ADDRESS] [--x URL] [--github URL]
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = path.dirname(fileURLToPath(import.meta.url));
const SRC = path.join(ROOT, 'src');

export async function build({ out = 'dist', ca, x, github } = {}) {
  const outDir = path.resolve(ROOT, out);
  if (!outDir.startsWith(ROOT + path.sep)) throw new Error('refusing to write outside the project folder: ' + outDir);
  const { REGISTER } = await import(pathToFileURL(path.join(SRC, 'js', 'register.js')).href + '?t=' + Math.random());
  const register = structuredClone(REGISTER);
  // overrides read the CURRENT record shape; nothing assumes the starting state
  if (ca) register.ca = { ...register.ca, state: 'stated', value: ca };
  if (x) register.x = { ...register.x, state: 'stated', url: x };
  if (github) register.github = { ...register.github, state: 'stated', url: github };

  await fs.rm(outDir, { recursive: true, force: true });
  for (const d of ['css', 'js', 'assets']) await fs.mkdir(path.join(outDir, d), { recursive: true });

  // css: tokens first (the only file with colour literals), then layout
  const css = (await fs.readFile(path.join(SRC, 'tokens.css'), 'utf8')) + '\n' + (await fs.readFile(path.join(SRC, 'styles.css'), 'utf8'));
  await fs.writeFile(path.join(outDir, 'css', 'app.css'), css);

  // js: copy modules, emit the (possibly overridden) register
  for (const f of await fs.readdir(path.join(SRC, 'js'))) {
    if (f === 'register.js') continue;
    await fs.copyFile(path.join(SRC, 'js', f), path.join(outDir, 'js', f));
  }
  await fs.writeFile(path.join(outDir, 'js', 'register.js'), `// generated by build.mjs from src/js/register.js\nexport const REGISTER = ${JSON.stringify(register, null, 2)};\n`);

  // assets: explicit copy, including the logo files the page references
  const assets = await fs.readdir(path.join(SRC, 'assets'));
  for (const f of assets) await fs.copyFile(path.join(SRC, 'assets', f), path.join(outDir, 'assets', f));
  for (const must of ['logo-128.png', 'logo-512.png', 'favicon.svg', 'apple-touch.png']) {
    await fs.access(path.join(outDir, 'assets', must)).catch(() => { throw new Error('logo/asset missing from build output: assets/' + must); });
  }

  // html
  const { renderPage } = await import(pathToFileURL(path.join(SRC, 'js', 'render.js')).href);
  const html = renderPage(await fs.readFile(path.join(SRC, 'index.html'), 'utf8'), register);
  if (/\{\{[A-Z_]+\}\}/.test(html)) throw new Error('unreplaced template placeholder in index.html');
  await fs.writeFile(path.join(outDir, 'index.html'), html);
  return { outDir, register };
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  const a = process.argv.slice(2), get = (k) => (a.includes(k) ? a[a.indexOf(k) + 1] : undefined);
  build({ out: get('--out'), ca: get('--ca'), x: get('--x'), github: get('--github') }).then(
    ({ outDir }) => console.log('build ok ->', path.relative(ROOT, outDir) || '.'),
    (e) => { console.error('build failed:', e.message); process.exit(1); },
  );
}
